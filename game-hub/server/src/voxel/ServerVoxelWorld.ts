/**
 * The server's view of a Voxelvale world: the seed's generated terrain plus
 * the authoritative edit list. A dirty flag tracks edits made since the last
 * save (see WorldStore).
 *
 * Chunks are kept as "views": the generated chunk with this world's edits
 * applied, in a numeric slot per chunk and a small LRU (design-voxel-mobs
 * §9.6). getBlock generates missing views on demand; the creature sim reads
 * through reader(), which never generates (unavailable chunks read as
 * Bedrock) and asks for them with warm(), generated within a time budget by
 * pumpWarm() every tick.
 */
import {
  type BlockEdit,
  type BlockQuery,
  blockIndex,
  blockInWorld,
  CHUNK_HEIGHT,
  chunkInWorld,
  chunkKey,
  createWorldGenerator,
  type GenVersion,
  LATEST_GEN_VERSION,
  packPos,
  toChunkCoord,
  toLocal,
  unpackPos,
  type VoxelMode,
  type WorldGenerator,
  WORLD_RADIUS_CHUNKS,
} from '@hub/shared';

/** Chunk cache floor (v2 generation costs about 2x v1, so more is kept). setCacheBudget may raise it. */
const MAX_CACHED_CHUNKS = 384;
const SIDE = WORLD_RADIUS_CHUNKS * 2;
const BEDROCK = 14;

const slotOf = (cx: number, cz: number) => (cx + WORLD_RADIUS_CHUNKS) * SIDE + (cz + WORLD_RADIUS_CHUNKS);

export class ServerVoxelWorld {
  readonly generator: WorldGenerator;
  /** packPos -> block id; the full history needed by late joiners. */
  private readonly edits = new Map<number, number>();
  /** Chunk slot -> packed positions of its edits (to build views). */
  private readonly editsByChunk = new Map<number, Set<number>>();
  /** packPos -> generated block under an edit (filled lazily for restored edits). */
  private readonly generatedAt = new Map<number, number>();
  /** Generated chunks with edits applied, by slot. */
  private readonly views: (Uint8Array | undefined)[] = new Array(SIDE * SIDE);
  /** LRU order of cached slots (insertion-ordered). */
  private readonly lru = new Map<number, true>();
  private readonly touchedTick = new Int32Array(SIDE * SIDE).fill(-1);
  /** Chunks outside the world (rare reads): generated, small separate cache. */
  private readonly outside = new Map<string, Uint8Array>();
  private readonly warmQueue = new Set<number>();
  private cacheBudget = MAX_CACHED_CHUNKS;
  /** Upper bound for pumpWarm set by the creature sim (ms; Infinity = the caller's). */
  warmBudgetMs = Infinity;
  private tickNo = 0;
  private _dirty = false;
  /** encodedEdits() result, dropped whenever the edit list changes. */
  private encoded: Uint8Array | null = null;
  /** Chunks generated by pumpWarm and its milliseconds (stats for logs). */
  warmStats = { chunks: 0, ms: 0 };

  constructor(
    readonly seed: number,
    readonly mode: VoxelMode,
    readonly maxEdits = 200_000,
    readonly genVersion: GenVersion = LATEST_GEN_VERSION,
  ) {
    this.generator = createWorldGenerator(seed, mode, genVersion);
  }

  // ---- fast access for the creature sim -----------------------------------------------

  /** Hot-loop block reader: cached views only (never generates); Bedrock where no view. */
  reader(): BlockQuery {
    const views = this.views;
    return (x, y, z) => {
      if (y < 0) return BEDROCK;
      if (y >= CHUNK_HEIGHT) return 0;
      const cx = x >> 4;
      const cz = z >> 4;
      if (cx < -WORLD_RADIUS_CHUNKS || cx >= WORLD_RADIUS_CHUNKS || cz < -WORLD_RADIUS_CHUNKS || cz >= WORLD_RADIUS_CHUNKS) return BEDROCK;
      const v = views[(cx + WORLD_RADIUS_CHUNKS) * SIDE + (cz + WORLD_RADIUS_CHUNKS)];
      return v ? v[((y << 4) + (z & 15)) * 16 + (x & 15)] : BEDROCK;
    };
  }

  /** Chunk data (with edits) is ready for the column. */
  hasChunkView(x: number, z: number): boolean {
    const cx = Math.floor(x) >> 4;
    const cz = Math.floor(z) >> 4;
    if (!chunkInWorld(cx, cz)) return false;
    return this.views[slotOf(cx, cz)] !== undefined;
  }

  /** Queue generation of a chunk (time-budgeted by pumpWarm). */
  warm(cx: number, cz: number): void {
    if (!chunkInWorld(cx, cz)) return;
    const s = slotOf(cx, cz);
    if (!this.views[s]) this.warmQueue.add(s);
  }

  /** Generate queued chunks for up to maxMs (called every tick by VoxelRoom). */
  pumpWarm(maxMs = 3): void {
    this.tickNo++;
    const budget = Math.min(maxMs, this.warmBudgetMs);
    if (budget <= 0 || this.warmQueue.size === 0) return;
    const t0 = performance.now();
    for (const s of this.warmQueue) {
      this.warmQueue.delete(s);
      if (!this.views[s]) {
        const cx = Math.floor(s / SIDE) - WORLD_RADIUS_CHUNKS;
        const cz = (s % SIDE) - WORLD_RADIUS_CHUNKS;
        this.view(cx, cz);
        this.warmStats.chunks++;
      }
      if (performance.now() - t0 >= budget) break;
    }
    this.warmStats.ms += performance.now() - t0;
  }

  /** Cache size in chunks (never below MAX_CACHED_CHUNKS). */
  setCacheBudget(chunks: number): void {
    this.cacheBudget = Math.max(MAX_CACHED_CHUNKS, Math.floor(chunks));
  }

  get cachedChunks(): number {
    return this.lru.size;
  }

  get editCount(): number {
    return this.edits.size;
  }

  /** True when the edit list changed since the last markClean(). */
  get dirty(): boolean {
    return this._dirty;
  }

  markClean(): void {
    this._dirty = false;
  }

  /** Flags unsaved changes again, e.g. after a failed save. */
  markDirty(): void {
    this._dirty = true;
  }

  getBlock(x: number, y: number, z: number): number {
    if (y < 0) return BEDROCK;
    if (y >= CHUNK_HEIGHT) return 0;
    const cx = toChunkCoord(x);
    const cz = toChunkCoord(z);
    const idx = blockIndex(toLocal(x), y, toLocal(z));
    if (!chunkInWorld(cx, cz)) return this.edits.get(packPos(x, y, z)) ?? this.outsideChunk(cx, cz)[idx];
    return this.view(cx, cz)[idx];
  }

  /** Records an edit. Returns false if the edit budget for this room is exhausted. */
  setBlock(x: number, y: number, z: number, id: number): boolean {
    const key = packPos(x, y, z);
    if (!this.edits.has(key) && this.edits.size >= this.maxEdits) return false;
    if (y < 0 || y >= CHUNK_HEIGHT) return true;
    const cx = toChunkCoord(x);
    const cz = toChunkCoord(z);
    const inWorld = chunkInWorld(cx, cz);
    // An edit that restores the generated block can be forgotten entirely.
    const generated = this.generatedValue(x, y, z, key);
    if (generated === id) {
      if (this.edits.delete(key)) {
        this.generatedAt.delete(key);
        if (inWorld) this.editsByChunk.get(slotOf(cx, cz))?.delete(key);
        this.changed();
      }
    } else if (this.edits.get(key) !== id) {
      if (!this.edits.has(key)) {
        this.generatedAt.set(key, generated);
        if (inWorld) this.indexEdit(slotOf(cx, cz), key);
      }
      this.edits.set(key, id);
      this.changed();
    }
    if (inWorld) {
      const v = this.views[slotOf(cx, cz)];
      if (v) v[blockIndex(toLocal(x), y, toLocal(z))] = id;
    }
    return true;
  }

  /**
   * Bulk-restores saved edits without marking the world dirty. Edits outside
   * the world are skipped and loading stops at the edit budget.
   * Returns the number of edits applied.
   */
  loadEdits(edits: Iterable<BlockEdit>): number {
    let applied = 0;
    for (const e of edits) {
      if (!blockInWorld(e.x, e.y, e.z)) continue;
      const key = packPos(e.x, e.y, e.z);
      if (!this.edits.has(key) && this.edits.size >= this.maxEdits) break;
      this.edits.set(key, e.id);
      this.indexEdit(slotOf(toChunkCoord(e.x), toChunkCoord(e.z)), key);
      applied++;
    }
    this.encoded = null;
    // Cached views predate these edits: rebuild them on demand.
    for (const s of this.lru.keys()) this.views[s] = undefined;
    this.lru.clear();
    return applied;
  }

  allEdits(): BlockEdit[] {
    const out: BlockEdit[] = [];
    for (const [key, id] of this.edits) {
      const [x, y, z] = unpackPos(key);
      out.push({ x, y, z, id });
    }
    return out;
  }

  /**
   * The edit list exactly as encodeEdits(allEdits(), true) would encode it
   * (u32 count, then 6-byte edits), written straight from the edit map without
   * intermediate objects. Cached until the next change, so late-join snapshots
   * and saves share one copy: callers must not modify it.
   */
  encodedEdits(): Uint8Array {
    if (this.encoded) return this.encoded;
    const out = new Uint8Array(4 + this.edits.size * 6);
    const view = new DataView(out.buffer);
    view.setUint32(0, this.edits.size, true);
    let o = 4;
    for (const [key, id] of this.edits) {
      const [x, y, z] = unpackPos(key);
      view.setInt16(o, x, true);
      view.setUint8(o + 2, y);
      view.setInt16(o + 3, z, true);
      view.setUint8(o + 5, id);
      o += 6;
    }
    return (this.encoded = out);
  }

  private changed(): void {
    this._dirty = true;
    this.encoded = null;
  }

  private indexEdit(slot: number, key: number): void {
    let set = this.editsByChunk.get(slot);
    if (!set) this.editsByChunk.set(slot, (set = new Set()));
    set.add(key);
  }

  /** The generated block at a cell, whether or not an edit covers it. */
  private generatedValue(x: number, y: number, z: number, key: number): number {
    const cx = toChunkCoord(x);
    const cz = toChunkCoord(z);
    const idx = blockIndex(toLocal(x), y, toLocal(z));
    if (!chunkInWorld(cx, cz)) return this.outsideChunk(cx, cz)[idx];
    if (!this.edits.has(key)) return this.view(cx, cz)[idx];
    const known = this.generatedAt.get(key);
    if (known !== undefined) return known;
    // Restored edit: generate the chunk once and remember every edited cell's original block.
    const raw = this.generator.generateChunk(cx, cz);
    for (const k of this.editsByChunk.get(slotOf(cx, cz)) ?? []) {
      if (this.generatedAt.has(k)) continue;
      const [ex, ey, ez] = unpackPos(k);
      this.generatedAt.set(k, raw[blockIndex(toLocal(ex), ey, toLocal(ez))]);
    }
    return this.generatedAt.get(key) ?? raw[idx];
  }

  /** The chunk view (generated + edits), generated now when missing. */
  private view(cx: number, cz: number): Uint8Array {
    const s = slotOf(cx, cz);
    let v = this.views[s];
    if (v) {
      // Refresh the LRU position at most once per tick.
      if (this.touchedTick[s] !== this.tickNo) {
        this.touchedTick[s] = this.tickNo;
        this.lru.delete(s);
        this.lru.set(s, true);
      }
      return v;
    }
    v = this.generator.generateChunk(cx, cz);
    const edits = this.editsByChunk.get(s);
    if (edits) {
      for (const k of edits) {
        const [x, y, z] = unpackPos(k);
        const i = blockIndex(toLocal(x), y, toLocal(z));
        if (!this.generatedAt.has(k)) this.generatedAt.set(k, v[i]);
        v[i] = this.edits.get(k)!;
      }
    }
    this.views[s] = v;
    this.lru.set(s, true);
    this.touchedTick[s] = this.tickNo;
    while (this.lru.size > this.cacheBudget) {
      const oldest = this.lru.keys().next().value as number;
      this.lru.delete(oldest);
      this.views[oldest] = undefined;
    }
    return v;
  }

  private outsideChunk(cx: number, cz: number): Uint8Array {
    const key = chunkKey(cx, cz);
    let c = this.outside.get(key);
    if (!c) {
      c = this.generator.generateChunk(cx, cz);
      if (this.outside.size > 16) this.outside.clear();
      this.outside.set(key, c);
    }
    return c;
  }
}
